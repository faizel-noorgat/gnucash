@pytest.mark.acceptance
@pytest.mark.rule("RPT-001")
def test_analytic_result_has_evidence_references():
    """Every AnalyticResult must carry evidence references."""
    result = AnalyticResult(
        query_kind=QueryKind.VARIANCE,
        metrics=[
            Metric(name="delta", value=Decimal("100"), unit="SGD", as_of=dt.date(2026, 9, 19))
        ],
        evidence=[
            EvidenceReference(
                kind="account",
                id="acc-001",
                description="Operating Expenses",
            )
        ],
    )
    assert len(result.evidence) == 1
    assert result.evidence[0].kind == "account"
    assert result.evidence[0].id == "acc-001"


