# ---------------------------------------------------------------------------
# RPT-001: Reports are deterministic
# ---------------------------------------------------------------------------


@pytest.mark.acceptance
@pytest.mark.rule("RPT-001")
def test_report_is_deterministic(tenant_id: str, today: dt.date):
    """Given the same definition + parameters + ledger state, the output
    is identical on every invocation.

    This test invokes the trial_balance generator twice with the same
    inputs and asserts the output is identical.
    """
    parameters = ReportParameters(
        date_from=dt.date(2026, 1, 1),
        date_to=today,
    )
    result_a = report_generator._trial_balance(
        tenant_id=tenant_id, parameters=parameters
    )
    result_b = report_generator._trial_balance(
        tenant_id=tenant_id, parameters=parameters
    )
    assert result_a.definition_code == result_b.definition_code
    assert result_a.parameters == result_b.parameters
    assert result_a.columns == result_b.columns
    assert result_a.rows == result_b.rows
    assert result_a.row_count == result_b.row_count


