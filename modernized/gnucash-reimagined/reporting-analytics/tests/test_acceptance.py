# RPT-002: Reports are tenant-scoped
# ---------------------------------------------------------------------------


@pytest.mark.acceptance
@pytest.mark.rule("RPT-002")
def test_report_is_tenant_scoped(tenant_id: str, today: dt.date):
    """A report query for tenant A must not include rows from tenant B.

    This test is a structural assertion: the SQL generated by the
    report generator includes a ``WHERE tenant_id = %(tenant_id)s``
    clause. We cannot test the actual isolation without a real
    Postgres with RLS policies loaded; that is covered by the
    integration test suite (marked ``@pytest.mark.rls``).
    """
    parameters = ReportParameters(
        date_from=dt.date(2026, 1, 1),
        date_to=today,
    )
    # The trial_balance SQL is a string; we assert it contains the
    # tenant filter.
    import inspect

    source = inspect.getsource(report_generator._trial_balance)
    assert "tenant_id = %(tenant_id)s" in source, (
        "trial_balance SQL must filter by tenant_id"
    )


# ---------------------------------------------------------------------------
# RPT-003: AI insights require evidence
# ---------------------------------------------------------------------------


@pytest.mark.acceptance
@pytest.mark.rule("RPT-003")
def test_insight_requires_evidence():
    """An AnalyticInsight must have at least one evidence reference.

    If the deterministic query produces no evidence, the insight must
    NOT be persisted — this prevents hallucinated insights.
    """
    query = AnalyticQuery(
        guid=uuid.uuid4(),
        tenant_id="tenant-test-0001",
        kind=QueryKind.ANOMALY,
        parameters={},
    )
    insight = AnalyticInsight(
        guid=uuid.uuid4(),
        tenant_id="tenant-test-0001",
        query=query,
        status="generated",
        evidence=[],  # Empty evidence — should fail.
        narrative="This is a hallucinated insight.",
    )
    with pytest.raises(ValueError, match="at least one evidence reference"):
        insight.save()


@pytest.mark.acceptance
@pytest.mark.rule("RPT-003")
def test_explainer_refuses_no_evidence():
    """The AI explainer must refuse to generate a narrative if the
    analytic result has no evidence.

    This is a safety check: the LLM must never be asked to explain
    nothing.
    """
    result = AnalyticResult(
        query_kind=QueryKind.ANOMALY,
        metrics=[Metric(name="outlier_count", value=0, unit="count", as_of=dt.date(2026, 9, 19))],
        evidence=[],  # Empty evidence.
    )
    with pytest.raises(EvidenceMissingError):
        ai_explainer.explain(result=result)


# ---------------------------------------------------------------------------
# RPT-004: Report lifecycle state transitions
# ---------------------------------------------------------------------------


@pytest.mark.acceptance
@pytest.mark.rule("RPT-004")
def test_report_lifecycle_transitions():
    """A ReportInstance must follow the allowed state transitions:

        pending → running → succeeded | failed
                  ↓
              cancelled (only from pending/running)
    """
    instance = ReportInstance(status=ReportStatus.PENDING)
    # Valid transitions.
    instance.transition_to(ReportStatus.RUNNING)
    assert instance.status == ReportStatus.RUNNING
    instance.transition_to(ReportStatus.SUCCEEDED)
    assert instance.status == ReportStatus.SUCCEEDED

    # Invalid transition: succeeded → pending.
    with pytest.raises(ValueError, match="cannot transition"):
        instance.transition_to(ReportStatus.PENDING)


@pytest.mark.acceptance
@pytest.mark.rule("RPT-004")
def test_report_can_be_cancelled_from_pending():
    """A pending report can be cancelled."""
    instance = ReportInstance(status=ReportStatus.PENDING)
    instance.transition_to(ReportStatus.CANCELLED)
    assert instance.status == ReportStatus.CANCELLED


@pytest.mark.acceptance
@pytest.mark.rule("RPT-004")
def test_report_cannot_be_cancelled_from_succeeded():
    """A succeeded report cannot be cancelled."""
    instance = ReportInstance(status=ReportStatus.SUCCEEDED)
    with pytest.raises(ValueError, match="cannot transition"):
        instance.transition_to(ReportStatus.CANCELLED)


# ---------------------------------------------------------------------------
# RPT-005: Async report generation
# ---------------------------------------------------------------------------


@pytest.mark.acceptance
@pytest.mark.rule("RPT-005")
def test_report_parameters_validation():
    """Report parameters must be validated before generation."""
    definition = ReportDefinition(
        guid=uuid.uuid4(),
        code="trial_balance",
        name="Trial Balance",
        report_type=ReportType.TRIAL_BALANCE,
        parameter_schema={},
        query_template="",
    )
    # Valid parameters.
    params = validate_parameters(
        definition,
        {"date_from": "2026-01-01", "date_to": "2026-09-19"},
    )
    assert params.date_from == dt.date(2026, 1, 1)
    assert params.date_to == dt.date(2026, 9, 19)

    # Invalid: date_from > date_to.
    with pytest.raises(ReportParametersInvalidError, match="date_from must not be after"):
        validate_parameters(
            definition,
            {"date_from": "2026-12-31", "date_to": "2026-01-01"},
        )


