# ---------------------------------------------------------------------------
# RPT-007: Golden accounting tests dependency
# ---------------------------------------------------------------------------


@pytest.mark.acceptance
@pytest.mark.rule("RPT-007")
@pytest.mark.golden_dependency
def test_golden_dependency_gate(tmp_path: Path):
    """The reporting context depends on the accounting engine's golden
    tests passing before any report that touches posted data can be
    considered correct.

    This test verifies the dependency-gate mechanism: if the golden
    manifest is missing or stale, tests marked with
    ``@pytest.mark.golden_dependency`` are skipped.
    """
    manifest_path = tmp_path / "golden.lock"
    # Simulate a missing manifest.
    assert not manifest_path.exists()
    # The gate should skip the test.
    # (In practice, the pytest plugin would check this before running.)
    # Here we just assert the mechanism exists.
    from reporting_analytics.services import golden_dependency

    assert golden_dependency.is_golden_green(manifest_path) is False

    # Simulate a green manifest.
    manifest_path.write_text("status=green\ncommit=abc123\n")
    assert golden_dependency.is_golden_green(manifest_path) is True


