"""Acceptance tests for the Reporting & Analytics bounded context.

These tests encode the behavior-contract rules that the reporting
context must satisfy. Each test is tagged with a rule ID; the rule
IDs are derived from the architectural requirements in
``REIMAGINED_ARCHITECTURE.md`` Section 6 and Section 9.7.

NOTE: The AI_NATIVE_SPEC does not define explicit ``BR-RPT-xxx`` rules
for the reporting context (unlike ``BR-ACCT-xxx`` for the accounting
engine). The rule IDs below are derived from the architectural
requirements and are marked as ``@pytest.mark.acceptance`` so they
can be run independently.

The rules are:

* RPT-001: Reports are deterministic — same input → same output.
* RPT-002: Reports are tenant-scoped — no cross-tenant leakage.
* RPT-003: AI insights require evidence — no hallucinated insights.
* RPT-004: Report lifecycle state transitions are explicit.
* RPT-005: Async report generation with proper state management.
* RPT-006: AI explainer is never asked to perform arithmetic.
* RPT-007: Golden accounting tests must pass before reporting on posted data.
"""

